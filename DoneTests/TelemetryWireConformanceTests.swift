        super.tearDown()
    }

    private func date(_ iso: String) -> Date {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime]
        return f.date(from: iso)!
    }

    private func stamp(build: String = "12") -> SpikeRunContext.Stamp {
        SpikeRunContext.Stamp(appVersion: "0.5.0", appBuild: build, appCommit: nil, deviceModel: "iPhone17,2",
                              osVersion: "26.0", timeZoneIdentifier: "America/Los_Angeles",
                              localeIdentifier: "en_US", buildConfiguration: "release")
    }

    private func run(
        id: UUID, spikeID: String, scenarioID: String, startedAt: Date, endedAt: Date?,
        variantID: String? = nil, coActive: [String]? = nil, metrics: [String: SpikeMetricValue],
        note: String? = nil, outcome: SpikeRunOutcome? = .completed, abortReason: SpikeAbortReason? = nil,
        kind: TelemetryRecordKind?, owner: String? = uid, day: (String, Int)? = ("2026-09-21", -420)
    ) -> SpikeRun {
        let s = stamp()
        var run = SpikeRun(
            id: id, spikeID: spikeID, scenarioID: scenarioID, variantID: variantID,
            startedAt: startedAt, endedAt: endedAt,
            appVersion: s.appVersion, appBuild: s.appBuild, appCommit: s.appCommit,
            deviceModel: s.deviceModel, osVersion: s.osVersion,
            timeZoneIdentifier: s.timeZoneIdentifier, localeIdentifier: s.localeIdentifier,
            buildConfiguration: s.buildConfiguration, coActiveSpikeIDs: coActive,
            metrics: metrics, note: note, outcome: outcome, abortReason: abortReason
        )
        run.ownerUID = owner
        run.kind = kind
        run.dayKey = day?.0
        run.dayTZOffsetMin = day?.1
        return run
    }

    // MARK: - The six records, through the production write paths

    /// daily_rollup: today's record is seeded on disk under the center's
    /// claim (so the id is fixed), the real center adopts it, two signals
    /// land, one flush appends revision 2 with the center's own envelope.
    private func writeDaily(clock: Date) throws {
        var counters = ResidentCounterSet()
        counters.tapCount = 3
        counters.meComputedVisible = 2
        counters.windowsOpened = 1
        counters.tapLagHistogram = try XCTUnwrap(ResidentLagHistogram(counts: [1, 2, 3, 4, 5, 6, 7, 8]))
        let seed = run(id: Self.dailyID, spikeID: FixObservationRegistry.residentDailySpikeID,
                       scenarioID: FixObservationRegistry.residentDailyScenarioID,
                       startedAt: date("2026-09-21T15:00:00Z"), endedAt: date("2026-09-21T15:01:00Z"),
                       metrics: counters.metrics, kind: .dailyRollup)
        XCTAssertTrue(SpikeRunStore.finishRun(seed, location: location), "seed must land")

        let center = ResidentObservationCenter(
            coordinator: SpikeSessionCoordinator(), store: nil, location: location, calendar: la,
            now: { clock }, mediaNow: { 0 }, ownerUID: { Self.uid }, stamp: { [unowned self] in self.stamp() }
        )
        centers.append(center)
        center.activate()
        SpikeProbe.emit(.counter(FixWatchSignalID.meComputedVisible))
        SpikeProbe.emit(.counter(FixWatchSignalID.meComputedVisible))
        center.flushDaily()
        center.deactivate()
    }

    /// window: metrics from the production aggregator over a two-tap window
    /// (one writing tap, one no-op tap whose settle frame never came), the
    /// envelope as the center stamps it.
    private func writeWindow() {
        var window = ResidentWindowModel(openedAtMedia: 1000.0, openedAt: date("2026-09-21T16:00:00Z"),
                                         triggerCommitEndMedia: 1000.5)
        window.noteSlot(.calendarEventLogRecords)
        window.noteSlot(.calendarEvents)
        var writing = Spike201GestureRecord(index: 0, firstChangedAt: 1001.0, firstLocationX: 40, lastChangedAt: 1001.02)
        writing.endedAt = 1001.05
        writing.commitStartedAt = 1001.06
        writing.commitEndedAt = 1001.0725
        writing.firstDeliveryLagMs = 4.2
        writing.firstFrameAfterCommitMs = 16.7
        writing.slotWrites = 2
        var noop = Spike201GestureRecord(index: 1, firstChangedAt: 1003.0, firstLocationX: 40, lastChangedAt: 1003.01)
        noop.endedAt = 1003.03
        noop.commitStartedAt = 1003.04
        noop.commitEndedAt = 1003.045
        noop.firstDeliveryLagMs = 7.9
        let metrics = ResidentWindowAggregates.metrics(window: window, records: [writing, noop],
                                                       closedAtMedia: 1006.0, probe: nil, closedByResign: false)
        let record = run(id: Self.windowID, spikeID: FixObservationRegistry.effortPathFixID,
                         scenarioID: FixObservationRegistry.windowScenarioID,
                         startedAt: date("2026-09-21T16:00:00Z"), endedAt: date("2026-09-21T16:00:06Z"),
                         coActive: [], metrics: metrics, kind: .window)
        XCTAssertTrue(SpikeRunStore.finishRun(record, location: location))
    }

    /// manual_run: exactly as a runner writes it — open record, then the
    /// closed one, no owner, no kind, no day (the store stamps the owner, the
    /// wire infers the kind and the day). Carries every free-text outlet: a
    /// note, a CSV-shaped `.string` metric, an abort reason.
    private func writeManual(id: UUID, startedAt: Date) {
        var open = run(id: id, spikeID: Spike201SignalID.spikeID, scenarioID: Spike201SignalID.scenarioID,
                       startedAt: startedAt, endedAt: nil, variantID: "B", coActive: [FixObservationRegistry.effortPathFixID],
                       metrics: [:], outcome: nil, kind: nil, owner: nil, day: nil)
        XCTAssertTrue(SpikeRunStore.beginRun(open, location: location))
        open.endedAt = startedAt.addingTimeInterval(40)
        open.outcome = .aborted
        open.abortReason = .stoppedBeforeTarget
        open.note = Self.manualNote
        open.metrics = ["tapCount": .number(40), "p50CommitMs": .number(12.5),
                        "gestureCsv": .string("idx,commitMs\n0,12.5")]
        XCTAssertTrue(SpikeRunStore.finishRun(open, location: location))
    }

    /// verdict_snapshot: the KIND is in the wire enum and the server's check
    /// constraint; no writer exists yet (design §6.2 is slice 3). The row
    /// below is what the wire produces for a record stamped with the kind.
    private func writeVerdict() {
        let record = run(id: Self.verdictID, spikeID: "fixwatch-verdict", scenarioID: "snapshot",
                         startedAt: date("2026-09-21T17:00:00Z"), endedAt: date("2026-09-21T17:00:00Z"),
                         metrics: ["effortPath.state": .number(2), "effortPath.alarm": .bool(false),
                                   "meTabGate.state": .number(3), "meTabGate.alarm": .bool(true)],
                         kind: .verdictSnapshot)
        XCTAssertTrue(SpikeRunStore.finishRun(record, location: location))
    }

    /// A line written before the chassis (no revision / kind / dayKey /
    /// installID / ownerUID, abort reason as the old prose literal), then
    /// re-appended through the store by a note edit — the only way such a
    /// line ever becomes uploadable (revision 1, design §7.2).
    private func writeLegacy() throws {
        let line = """
        {"id":"\(Self.legacyID.uuidString)","spikeID":"\(Spike201SignalID.spikeID)","scenarioID":"\(Spike201SignalID.scenarioID)",\
        "variantID":"A","startedAt":"2026-09-20T18:00:00Z","endedAt":"2026-09-20T18:00:40Z","appVersion":"0.5.0","appBuild":"9",\
        "deviceModel":"iPhone17,2","osVersion":"26.0","timeZoneIdentifier":"America/Los_Angeles","localeIdentifier":"en_US",\
        "buildConfiguration":"release","coActiveSpikeIDs":["\(FixObservationRegistry.effortPathFixID)"],\
        "metrics":{"tapCount":40,"p50CommitMs":11.5},"note":"legacy note","outcome":"aborted",\
        "abortReason":"stopped manually before 40 characters"}\n
        """
        let url = location.directory.appendingPathComponent("\(Spike201SignalID.spikeID).jsonl")
        let handle = try FileHandle(forWritingTo: url)
        defer { try? handle.close() }
        _ = try handle.seekToEnd()
        try handle.write(contentsOf: Data(line.utf8))
        XCTAssertTrue(SpikeRunStore.setNote(Self.legacyNoteEdit, forRunID: Self.legacyID,
                                            spikeID: Spike201SignalID.spikeID, location: location))
    }

    private func load(_ spikeID: String, _ id: UUID) throws -> SpikeRun {
        try XCTUnwrap(SpikeRunStore.loadRuns(spikeID: spikeID, location: location).first { $0.id == id }, "\(id) on disk")
    }

    /// The uploader's serialization, verbatim (TelemetryUploader.runBatch),
    /// with the fixed calendar in the fallback seam.
    private func wireRow(_ run: SpikeRun, noteOptIn: Bool, now: Date) -> [String: Any] {
        let calendar = la!
        return TelemetryRedactor.redact(
            row: TelemetryWire.row(for: run, userID: Self.uid, installID: Self.installID, now: now) { startedAt in
                TelemetryClaimKey.dayKey(forDayStart: calendar.startOfDay(for: startedAt), calendar: calendar)
            },
            noteOptIn: noteOptIn,
            allowedStringKeys: TelemetryRedactor.observatoryFixedFormatStringKeys
        )
    }

    private struct Produced {
        let rows: [[String: Any]]
        let json: Data
    }

    private func produce() throws -> Produced {
        let clock = date("2026-09-21T17:05:00Z")
        try writeDaily(clock: clock)
        writeWindow()
        writeManual(id: Self.manualOptInID, startedAt: date("2026-09-21T16:30:00Z"))
        writeManual(id: Self.manualOptOutID, startedAt: date("2026-09-21T16:40:00Z"))
        writeVerdict()
        try writeLegacy()

        let daily = try load(FixObservationRegistry.residentDailySpikeID, Self.dailyID)
        let window = try load(FixObservationRegistry.effortPathFixID, Self.windowID)
        let optIn = try load(Spike201SignalID.spikeID, Self.manualOptInID)
        let optOut = try load(Spike201SignalID.spikeID, Self.manualOptOutID)
        let verdict = try load("fixwatch-verdict", Self.verdictID)
        let legacy = try load(Spike201SignalID.spikeID, Self.legacyID)

        // Liveness of the production paths that stamped these records.
        XCTAssertEqual(daily.revision, 2, "seed + the center's flush")
        XCTAssertEqual(daily.metrics["meComputedVisible"], .number(4), "2 seeded + 2 emitted through the center")
        XCTAssertEqual(daily.endedAt, clock, "the flush closed the line at the injected clock")
        XCTAssertEqual(optIn.revision, 2, "open + closed records")
        XCTAssertEqual(optIn.ownerUID, Self.uid, "the store stamped the runner's owner-less record")
        XCTAssertNil(optIn.kind, "the runner stamps no kind")
        XCTAssertEqual(legacy.revision, 1, "a pre-chassis line re-appended once")
        XCTAssertEqual(legacy.abortReason, .stoppedBeforeTarget, "the old literal decodes to its case")
        XCTAssertNil(legacy.dayKey)
        XCTAssertEqual(legacy.installID, Self.installID)
        for record in [daily, window, optIn, optOut, verdict, legacy] {
            XCTAssertEqual(record.installID, Self.installID, "\(record.id): the store stamped the pre-written install id")
        }

        let rows = [
            wireRow(daily, noteOptIn: false, now: clock),
            wireRow(window, noteOptIn: false, now: clock),
            wireRow(optIn, noteOptIn: true, now: clock),
            wireRow(optOut, noteOptIn: false, now: clock),
            wireRow(verdict, noteOptIn: false, now: clock),
            wireRow(legacy, noteOptIn: false, now: clock),
        ]
        var json = try JSONSerialization.data(withJSONObject: rows, options: [.prettyPrinted, .sortedKeys])
        json.append(0x0A)
        return Produced(rows: rows, json: json)
    }

    // MARK: - The fixture file is this test's output, byte for byte

    func testTheRepoFixtureIsExactlyWhatTheClientProduces() throws {
        let produced = try produce()
        let url = repoRoot.appendingPathComponent(Self.fixtureRelativePath)
        if ProcessInfo.processInfo.environment["TELEMETRY_WIRE_FIXTURE_WRITE"] == "1" {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try produced.json.write(to: url)
            XCTAssertTrue(FileManager.default.fileExists(atPath: url.path), "wrote \(url.path)")
            return
        }
        let onDisk = try Data(contentsOf: url)
        if onDisk != produced.json {
            let a = String(decoding: onDisk, as: UTF8.self).components(separatedBy: "\n")
            let b = String(decoding: produced.json, as: UTF8.self).components(separatedBy: "\n")
            let firstDiff = zip(a.indices, b.indices).first { a[$0] != b[$1] }.map(\.0) ?? min(a.count, b.count)
            XCTFail("""
            wire_rows.json differs from the client's output at line \(firstDiff + 1):
              file:   \(firstDiff < a.count ? a[firstDiff] : "<EOF>")
              client: \(firstDiff < b.count ? b[firstDiff] : "<EOF>")
            Regenerate with TEST_RUNNER_TELEMETRY_WIRE_FIXTURE_WRITE=1 and re-run telemetry_wire_conformance.sql.
            """)
        }
    }

    // MARK: - Contract §2 on every row

    func testEveryRowObeysTheColumnContract() throws {
        let rows = try produce().rows
        XCTAssertEqual(rows.count, 6)
        let dayKey = try NSRegularExpression(pattern: "^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
        for (index, row) in rows.enumerated() {
            let keys = Set(row.keys)
            XCTAssertTrue(keys.isSubset(of: Self.contractColumns), "row \(index): unknown columns \(keys.subtracting(Self.contractColumns))")
            XCTAssertTrue(Self.requiredColumns.isSubset(of: keys), "row \(index): missing \(Self.requiredColumns.subtracting(keys))")
            let revision = try XCTUnwrap(row["revision"] as? NSNumber, "row \(index) revision").intValue
            XCTAssertGreaterThanOrEqual(revision, 1, "row \(index): wire §2 revision from 1")
            let day = try XCTUnwrap(row["day_key"] as? String)
            XCTAssertEqual(dayKey.numberOfMatches(in: day, range: NSRange(day.startIndex..., in: day)), 1, "row \(index): day_key \(day)")
            XCTAssertTrue(["debug", "release"].contains(row["build_configuration"] as? String ?? ""), "row \(index)")
            XCTAssertNotNil(TelemetryRecordKind(rawValue: row["kind"] as? String ?? ""), "row \(index): kind")
            XCTAssertEqual(row["user_id"] as? String, Self.uid)
            XCTAssertEqual(row["install_id"] as? String, Self.installID.uuidString.lowercased())
        }
        XCTAssertEqual(rows.map { $0["kind"] as? String },
                       ["daily_rollup", "window", "manual_run", "manual_run", "verdict_snapshot", "manual_run"])
        XCTAssertEqual(rows.map { $0["revision"] as? Int }, [2, 1, 2, 2, 1, 1])
    }

    /// Opt-out rows carry no `note` KEY (not an empty value); the one opt-in
    /// row carries exactly the human's note. The CSV `.string` metric and the
    /// legacy prose are gone from every row.
    func testNoteAppearsOnlyOnTheOptInRowAndNoOtherFreeTextLeaves() throws {
        let rows = try produce().rows
        for (index, row) in rows.enumerated() where index != 2 {
            XCTAssertFalse(row.keys.contains("note"), "row \(index) must not have a note key")
        }
        XCTAssertEqual(rows[2]["note"] as? String, Self.manualNote, "positive control: the opt-in manual run")
        let bytes = String(decoding: try JSONSerialization.data(withJSONObject: rows, options: [.sortedKeys]), as: UTF8.self)
        XCTAssertFalse(bytes.contains("gestureCsv"), "the CSV metric key must not survive redaction")
        XCTAssertFalse(bytes.contains("idx,commitMs"))
        XCTAssertFalse(bytes.contains("legacy note"))
        XCTAssertFalse(bytes.contains("stopped manually"), "the legacy prose is replaced by its wire token")
        XCTAssertTrue(bytes.contains("stopped_before_target"), "positive control: the token is on the wire")
        XCTAssertEqual(bytes.components(separatedBy: Self.manualNote).count - 1, 1, "the note appears exactly once")
    }

    /// Every String leaf on every row is a known identifier, a fixed-format
    /// value, or (opt-in row only) the note — spelled as the pattern the
    /// server relies on (the pooled-buckets regex, the %.1f lists).
    func testEveryStringLeafIsWhitelistedByShape() throws {
        let rows = try produce().rows
        let histogram = try NSRegularExpression(pattern: "^[0-9]+( [0-9]+)*$")
        let numberList = try NSRegularExpression(pattern: "^-?[0-9]+\\.[0-9]( -?[0-9]+\\.[0-9])*$")
        let identifier = try NSRegularExpression(pattern: "^[A-Za-z0-9,._-]{1,64}$")
        let version = try NSRegularExpression(pattern: "^[0-9.-]{1,64}$")
        let iso = try NSRegularExpression(pattern: "^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:.]+Z$")
        func matches(_ re: NSRegularExpression, _ s: String) -> Bool {
            re.numberOfMatches(in: s, range: NSRange(s.startIndex..., in: s)) == 1
        }
        var violations: [String] = []
        for (index, row) in rows.enumerated() {
            for (column, value) in row {
                switch column {
                case "metrics":
                    for (key, leaf) in try XCTUnwrap(value as? [String: Any]) {
                        guard let text = leaf as? String else { continue }
                        let ok: Bool
                        if ResidentCounterSet.fixedFormatStringKeys.contains(key) {
                            ok = matches(histogram, text)
                        } else if ResidentWindowAggregates.fixedFormatStringKeys.contains(key) {
                            ok = matches(numberList, text)
                        } else {
                            ok = false
                        }
                        if !ok { violations.append("row \(index) metrics.\(key) = \(text)") }
                    }
                case "context":
                    let context = try XCTUnwrap(value as? [String: Any])
                    for id in context["co_active_spike_ids"] as? [String] ?? [] where !matches(identifier, id) {
                        violations.append("row \(index) context.co_active_spike_ids \(id)")
                    }
                    if let reason = context["abort_reason"] as? String, !SpikeAbortReason.wireValues.contains(reason) {
                        violations.append("row \(index) context.abort_reason \(reason)")
                    }
                    if let variant = context["variant_id"] as? String, !matches(identifier, variant) {
                        violations.append("row \(index) context.variant_id \(variant)")
                    }
                    for key in context.keys where !["co_active_spike_ids", "abort_reason", "variant_id", "app_commit"].contains(key) {
                        violations.append("row \(index) context.\(key) is not a contract key")
                    }
                case "note":
                    if index != 2 { violations.append("row \(index) note") }
                default:
                    guard let text = value as? String else { continue }
                    let ok: Bool
                    switch column {
                    case "user_id", "run_id", "install_id": ok = UUID(uuidString: text) != nil && text == text.lowercased()
                    case "kind": ok = TelemetryRecordKind(rawValue: text) != nil
                    case "spike_id", "scenario_id", "device_model": ok = matches(identifier, text)
                    case "day_key", "app_version", "os_version": ok = matches(version, text)
                    case "build_configuration": ok = text == "debug" || text == "release"
                    case "outcome": ok = SpikeRunOutcome(rawValue: text) != nil
                    case "started_at", "ended_at", "client_updated_at": ok = matches(iso, text)
                    default: ok = false
                    }
                    if !ok { violations.append("row \(index) \(column) = \(text)") }
                }
            }
        }
        XCTAssertEqual(violations, [], "string leaves outside the whitelist")
    }

    // MARK: - Contract §4: metric keys and value shapes against the registry

    private struct RegistryEntry: Decodable {
        let key: String
        let kind: String
        let value_schema: String
        let spike_id: String
    }

    /// The daily row carries EXACTLY the registered resident-daily keys (a
    /// key added on one side only fails here); the window row's keys are all
    /// registered; every value's JSON shape is its registered value_schema —
    /// which is what counter_long's numeric cast and the pooled-buckets
    /// regex assume.
    func testMetricKeysAndValueShapesMatchTheKeyRegistry() throws {
        let registry = try JSONDecoder().decode([RegistryEntry].self,
                                                from: Data(contentsOf: repoRoot.appendingPathComponent(Self.registryRelativePath)))
        XCTAssertGreaterThan(registry.count, 0, "liveness: the registry file has rows")
        let rows = try produce().rows
        let bySpike = Dictionary(grouping: registry, by: \.spike_id)
        let daily = try XCTUnwrap(rows[0]["metrics"] as? [String: Any])
        let dailyRegistered = Set((bySpike[FixObservationRegistry.residentDailySpikeID] ?? []).map(\.key))
        XCTAssertEqual(Set(daily.keys), dailyRegistered, "resident-daily keys: client vs registry, both directions")
        XCTAssertEqual(Set(daily.keys), Set(ResidentCounterSet().metrics.keys).union(FollowerStatTable.dailyKeys),
                       "and the writer emits every one: the counters and the follower probe's day keys (perf batch 2a)")

        let window = try XCTUnwrap(rows[1]["metrics"] as? [String: Any])
        let windowRegistered = Set((bySpike[FixObservationRegistry.effortPathFixID] ?? []).map(\.key))
        XCTAssertTrue(Set(window.keys).isSubset(of: windowRegistered), "unregistered window keys: \(Set(window.keys).subtracting(windowRegistered))")
        XCTAssertGreaterThanOrEqual(window.count, 12, "liveness: the aggregator wrote the unconditional keys")

        let histogram = try NSRegularExpression(pattern: "^[0-9]+( [0-9]+)*$")
        let numberList = try NSRegularExpression(pattern: "^-?[0-9]+\\.[0-9]( -?[0-9]+\\.[0-9])*$")
        var violations: [String] = []
        for (rowIndex, metrics) in [(0, daily), (1, window)] {
            for (key, value) in metrics {
                guard let entry = registry.first(where: { $0.key == key }) else { continue }
                let ok: Bool
                switch entry.value_schema {
                case "number":
                    ok = (value as? NSNumber).map { CFGetTypeID($0) != CFBooleanGetTypeID() } ?? false
                case "bool":
                    ok = (value as? NSNumber).map { CFGetTypeID($0) == CFBooleanGetTypeID() } ?? false
                case "fixed_string":
                    ok = (value as? String).map { histogram.numberOfMatches(in: $0, range: NSRange($0.startIndex..., in: $0)) == 1 } ?? false
                case "number_list":
                    ok = (value as? String).map { numberList.numberOfMatches(in: $0, range: NSRange($0.startIndex..., in: $0)) == 1 } ?? false
                default:
                    ok = false
                }
                if !ok { violations.append("row \(rowIndex) \(key) (\(entry.kind)/\(entry.value_schema)) = \(value)") }
            }
        }
        XCTAssertEqual(violations, [])
        // Hand-computed shapes of the two aggregators' outputs on this fixture.
        XCTAssertEqual(daily["tapLagBuckets"] as? String, "1 2 3 4 5 6 7 8")
        XCTAssertEqual(daily["dragLagBuckets"] as? String, "0 0 0 0 0 0 0 0")
        XCTAssertEqual((daily["meComputedVisible"] as? NSNumber)?.intValue, 4)
        XCTAssertEqual(window["wCommitMs"] as? String, "12.5", "the writing tap's commit only")
        XCTAssertEqual(window["wLagMs"] as? String, "4.2 7.9", "both taps' first delivery lag")
        XCTAssertEqual(window["wFrameAfterCommitMs"] as? String, "16.7", "the no-op tap's frame never came")
        XCTAssertEqual((window["wTapsMissingFrameAfterCommit"] as? NSNumber)?.intValue, 1)
        XCTAssertEqual(window["wContaminated"] as? Bool, false)
        XCTAssertNil(window["wP50FrameDeltaMs"], "no probe → no frame statistics")
    }

