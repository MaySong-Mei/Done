//
//  TelemetryWireConformanceTests.swift
//  DoneTests
//
//  gh#273 — the client → server CONTRACT witness (Docs/telemetry/
//  01-wire-contract.md §2, §4). Six representative records are produced
//  through the production paths (the store stamps revision / install id /
//  owner; the center writes the daily; `ResidentWindowAggregates` writes the
//  window metrics; a pre-chassis line is re-appended and inferred), then
//  serialized EXACTLY as the uploader does (`TelemetryWire.row` →
//  `TelemetryRedactor.redact`). The rows are compared BYTE FOR BYTE with
//  `done-mcp/supabase/tests/fixtures/wire_rows.json`, which the SQL bench
//  `telemetry_wire_conformance.sql` inserts into the real `public.spike_runs`
//  as a user and reads back through the views. The file is generated by this
//  test (TEST_RUNNER_TELEMETRY_WIRE_FIXTURE_WRITE=1), never by hand: a hand
//  edit fails the comparison, a client change that moves a byte fails it too
//  and the SQL side is then re-run against the regenerated file.
//
//  Every date and id is fixed; the day boundary calendar is Los Angeles
//  (the uploader's own fallback uses `Calendar.current`, which this file
//  replaces with the fixed calendar through the same closure seam).
//

